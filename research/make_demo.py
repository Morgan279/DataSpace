"""Create a tiny synthetic fixture; it is not a DataSpace benchmark task."""
import argparse
import json
from pathlib import Path

from provenance import file_sha256, tree_sha256


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    root = args.output.resolve()
    root.mkdir(parents=True, exist_ok=False)
    task = root / "input/task_1"
    (task / "context").mkdir(parents=True)
    (task / "task.json").write_text(json.dumps({"question": "Sum food amounts by region."}) + "\n", encoding="utf-8")
    (task / "context/sales.csv").write_text(
        "region,category,amount\nNorth,food,2\nNorth,food,3\nSouth,food,7\nSouth,other,20\n",
        encoding="utf-8",
    )
    gold = root / "output/task_1/gold.csv"
    gold.parent.mkdir(parents=True)
    gold.write_text("region,amount\nNorth,5\nSouth,7\n", encoding="utf-8")
    config = root / "evaluation/configs/task_1.json"
    config.parent.mkdir(parents=True)
    config.write_text(json.dumps({
        "schema_version": "1.0", "task_id": "task_1", "order_sensitive": False,
        "columns": [
            {"gold_index": 0, "gold_name": "region", "type": "text"},
            {"gold_index": 1, "gold_name": "amount", "type": "number", "comparison": {"mode": "integer"}},
        ],
    }, indent=2) + "\n", encoding="utf-8")
    manifest = {
        "schema_version": 1,
        "source": {"kind": "synthetic", "description": "Generated by research/make_demo.py; not DataSpace."},
        "tasks": [{"task_id": "task_1", "case": "synthetic_sales", "input_tree_sha256": tree_sha256(task),
                   "gold_sha256": file_sha256(gold), "config_sha256": file_sha256(config)}],
    }
    (root / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Created synthetic fixture and manifest: {root}")


if __name__ == "__main__":
    main()
